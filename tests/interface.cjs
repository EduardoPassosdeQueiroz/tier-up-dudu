 await page.evaluate(d=>renderState({...d,themeVotes:1}),d);
 assert.equal(await page.locator('#answerText').inputValue(),'Minha resposta não pode sumir');
 assert.equal(await page.locator('#answerText').evaluate(el=>el.selectionStart),7);
 assert.equal(await page.locator('#answerText').evaluate(el=>document.activeElement===el),true);
 await page.evaluate(d=>renderState({...d,revision:2,currentTheme:'Bebidas'}),d);
 assert.equal(await page.locator('#answerText').inputValue(),'');
 const discussion={...d,phase:'discussing',discussingPlayerName:'Bia',discussingText:'<img src=x onerror=alert(1)>',judgeName:'Ana',iAmJudge:true,board:[{placed:'E',text:'Pizza de banana',playerName:'Caio'}]};
